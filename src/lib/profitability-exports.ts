const excelHeaderFill: ExcelJS.Fill = {
  type: "pattern",
  pattern: "solid",
  fgColor: { argb: "FF435266" },
};

const excelSectionFill: ExcelJS.Fill = {
  type: "pattern",
  pattern: "solid",
  fgColor: { argb: "FFEAF2F7" },
};

function argb(hex: string) {
  return `FF${hex.replace("#", "").toUpperCase()}`;
}

function currencyFormat(currency: string) {
  const safeCurrency = currency.replace(/[^A-Z]/gi, "").slice(0, 6) || "CUR";
  return `"${safeCurrency}" #,##0.00;[Red]("${safeCurrency}" #,##0.00);-`;
}

function styleHeaderRow(row: ExcelJS.Row) {
  row.height = 24;
  row.eachCell((cell) => {
    cell.fill = excelHeaderFill;
    cell.font = { bold: true, color: { argb: "FFFFFFFF" }, size: 10 };
    cell.alignment = { vertical: "middle", horizontal: "left" };
    cell.border = { bottom: { style: "medium", color: { argb: "FFEF7D00" } } };
  });
}

function prepareDataSheet(
  workbook: ExcelJS.Workbook,
  name: string,
  columns: Array<{ header: string; key: string; width: number }>,
  lang: ReportLocale,
) {
  const sheet = workbook.addWorksheet(name, {
    views: [{ state: "frozen", ySplit: 1, showGridLines: false, rightToLeft: lang === "ar" }],
  });
  sheet.columns = columns;
  styleHeaderRow(sheet.getRow(1));
  sheet.autoFilter = { from: "A1", to: `${sheet.getColumn(columns.length).letter}1` };
  sheet.pageSetup = { orientation: "landscape", fitToPage: true, fitToWidth: 1, fitToHeight: 0 };
  return sheet;
}

function styleDataRows(sheet: ExcelJS.Worksheet, headerRows = 1) {
  sheet.eachRow((row, rowNumber) => {
    if (rowNumber <= headerRows) return;
    row.height = 21;
    row.eachCell((cell) => {
      cell.font = { name: "Arial", size: 9.5, color: { argb: "FF171717" } };
      cell.alignment = { vertical: "middle", horizontal: "left" };
      cell.border = { bottom: { style: "hair", color: { argb: "FFD8DEE6" } } };
      if (rowNumber % 2 === 0) cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF7F9FB" } };
    });
  });
}

function styleMoneyColumn(sheet: ExcelJS.Worksheet, keys: string[], format: string) {
  for (const key of keys) {
    const column = sheet.getColumn(key);
    column.numFmt = format;
    column.alignment = { horizontal: "right" };
  }
}

function addEmptySheetMessage(sheet: ExcelJS.Worksheet, lastColumn: string, message: string) {
  sheet.addRow([message]);
  sheet.mergeCells(`A2:${lastColumn}2`);
  const cell = sheet.getCell("A2");
  cell.font = { italic: true, color: { argb: argb(palette.gray) } };
  cell.alignment = { vertical: "middle", horizontal: "left" };
}

