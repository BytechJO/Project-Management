function formatDate(date: Date | null | undefined) {
  if (!date) return "-";
  return new Intl.DateTimeFormat("en-GB", {
    year: "numeric",
    month: "short",
    day: "numeric",
    timeZone: "UTC",
  }).format(date);
}

function formatIsoDate(date: Date | null | undefined) {
  return date ? date.toISOString().slice(0, 10) : "-";
}

function money(value: number, currency: string) {
  return `${currency} ${new Intl.NumberFormat("en-JO", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(value)}`;
}

function hours(minutes: number) {
  return `${(minutes / 60).toFixed(1)} h`;
}

function localizedText(value: string, lang: ReportLocale) {
  if (lang !== "ar" || !/[\u0600-\u06ff]/.test(value)) return value;
  return value
    .split("\n")
    .map((line) => line.trim().split(/\s+/).reverse().join(" "))
    .join("\n");
}

function reportPeriod(report: ProjectProfitabilityReport, lang: ReportLocale) {
  if (!report.range.from && !report.range.to) return copy[lang].fullPeriod;
  return `${report.range.from ? formatDate(report.range.from) : "Start"} - ${report.range.to ? formatDate(report.range.to) : "Today"}`;
}

type PdfColumn = {
  key: string;
  header: string;
  width: number;
  align?: "left" | "right" | "center";
};

function createPdf(lang: ReportLocale, report: ProjectProfitabilityReport) {
  const doc = new PDFDocument({
    size: "A4",
    margins: { top: 42, right: 46, bottom: 48, left: 46 },
    bufferPages: true,
    info: {
      Title: `${copy[lang].title} - ${report.summary.project.name}`,
      Author: "Bytech",
      Creator: "Bytech Project Management",
    },
  });
  doc.registerFont("Brand", lang === "ar" ? arabicFont : brandFont);
  doc.font("Brand");
  return doc;
}

function pdfSectionTitle(doc: PDFKit.PDFDocument, title: string, y: number, lang: ReportLocale) {
  doc.fillColor(palette.primary).fontSize(11).text(localizedText(title, lang), 46, y, {
    width: 503,
    align: lang === "ar" ? "right" : "left",
  });
  doc.moveTo(46, y + 18).lineTo(549, y + 18).lineWidth(1).strokeColor(palette.orange).stroke();
  return y + 27;
}

function pdfTable(
  doc: PDFKit.PDFDocument,
  title: string,
  columns: PdfColumn[],
  rows: Array<Record<string, string>>,
  startY: number,
  lang: ReportLocale,
) {
  let y = startY;
  const rowHeight = 25;
  const headerHeight = 23;

  const drawTableHeader = () => {
    doc.rect(46, y, 503, headerHeight).fill(palette.primary);
    let x = 46;
    for (const column of columns) {
      doc.fillColor(palette.white).fontSize(7.5).text(localizedText(column.header, lang), x + 5, y + 7, {
        width: column.width - 10,
        align: column.align ?? (lang === "ar" ? "right" : "left"),
        lineBreak: false,
        ellipsis: true,
      });
      x += column.width;
    }
    y += headerHeight;
  };

  const minimumTableHeight = 27 + headerHeight + rowHeight;
  if (y + minimumTableHeight > 744) {
    doc.addPage();
    y = 46;
  }
  y = pdfSectionTitle(doc, title, y, lang);
  drawTableHeader();

  if (!rows.length) {
    doc.rect(46, y, 503, rowHeight).fillAndStroke(palette.soft, palette.line);
    doc.fillColor(palette.gray).fontSize(8).text(localizedText(copy[lang].noRows, lang), 52, y + 8, {
      width: 491,
      align: lang === "ar" ? "right" : "left",
    });
    return y + rowHeight + 15;
  }

  for (const [index, row] of rows.entries()) {
    if (y + rowHeight > 744) {
      doc.addPage();
      y = 46;
      y = pdfSectionTitle(doc, title, y, lang);
      drawTableHeader();
    }
    doc.rect(46, y, 503, rowHeight)
      .fillAndStroke(index % 2 === 0 ? palette.white : palette.soft, palette.line);
    let x = 46;
    for (const column of columns) {
      doc.fillColor(palette.ink).fontSize(7.4).text(localizedText(row[column.key] ?? "-", lang), x + 5, y + 8, {
        width: column.width - 10,
        align: column.align ?? (lang === "ar" ? "right" : "left"),
        lineBreak: false,
        ellipsis: true,
      });
      x += column.width;
    }
    y += rowHeight;
  }
  return y + 15;
}

function addPdfFooters(doc: PDFKit.PDFDocument, lang: ReportLocale) {
  const pages = doc.bufferedPageRange();
  for (let index = pages.start; index < pages.start + pages.count; index += 1) {
    doc.switchToPage(index);
    doc.moveTo(46, 768).lineTo(549, 768).lineWidth(0.7).strokeColor(palette.line).stroke();
    doc.fillColor(palette.gray).fontSize(8).text(localizedText(copy[lang].generated, lang), 46, 777, {
      width: 360,
      align: lang === "ar" ? "right" : "left",
      lineBreak: false,
    });
    doc.text(`${copy[lang].page} ${index + 1} / ${pages.count}`, 430, 777, { width: 119, align: "right", lineBreak: false });
  }
}

function finishPdf(doc: PDFKit.PDFDocument, lang: ReportLocale) {
  return new Promise<Uint8Array>((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => chunks.push(chunk));
    doc.on("end", () => resolve(new Uint8Array(Buffer.concat(chunks))));
    doc.on("error", reject);
    addPdfFooters(doc, lang);
    doc.end();
  });
}

